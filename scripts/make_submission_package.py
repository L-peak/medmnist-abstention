"""Build the Elsevier submission package for CMPB and verify that it compiles.

    python scripts/make_submission_package.py

The CMPB guide requires an editable source file (".tex for LaTeX"; "A PDF is not an
acceptable source file"), figures as separate files with a logical naming convention,
highlights as a separate editable file, and the competing-interest declaration from
Elsevier's declarations tool (that last one must be generated by the author at
https://declarations.elsevier.com/, it cannot be produced here).

Everything the LaTeX build needs is copied into submission/ (main.tex, references.bib,
figures/, tables/) and then compiled in a clean temporary directory; the script fails
if that build reports errors or undefined references.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
PACKAGE = ROOT / "submission"


def copy_tree() -> list[str]:
    """(Re)create submission/ with exactly the files the journal needs."""
    if PACKAGE.exists():
        shutil.rmtree(PACKAGE)
    (PACKAGE / "figures").mkdir(parents=True)
    (PACKAGE / "tables").mkdir(parents=True)

    copied: list[str] = []
    for name in ("main.tex", "references.bib"):
        shutil.copy2(PAPER / name, PACKAGE / name)
        copied.append(name)
    for table in sorted((PAPER / "tables").glob("*.tex")):
        shutil.copy2(table, PACKAGE / "tables" / table.name)
        copied.append(f"tables/{table.name}")
    for figure in sorted((PAPER / "figures").glob("Figure_*.pdf")):
        shutil.copy2(figure, PACKAGE / "figures" / figure.name)
        copied.append(f"figures/{figure.name}")
    # Compiled review copy (the guide requires the source as well; a PDF alone is not
    # an acceptable source file, but the compiled paper is still useful to reviewers).
    shutil.copy2(PAPER / "main.pdf", PACKAGE / "main.pdf")
    copied.append("main.pdf (compiled review copy)")
    return copied


def write_docx() -> list[str]:
    """Highlights and cover letter as editable files (the guide asks for editable)."""
    from docx import Document

    highlights = [line.strip() for line in
                  (PAPER / "highlights.txt").read_text(encoding="utf-8").splitlines()
                  if line.strip() and line.strip().lower() != "highlights"]
    document = Document()
    document.add_heading("Highlights", level=1)
    for line in highlights:
        document.add_paragraph(line, style="List Bullet")
    document.save(PACKAGE / "highlights.docx")

    cover = Document()
    for block in (PAPER / "cover_letter.md").read_text(encoding="utf-8").split("\n\n"):
        text = block.strip()
        if not text or text.startswith("#"):
            continue
        text = re.sub(r"\*\*(.+?)\*\*", r"\1", text).replace("---", "-")
        cover.add_paragraph(" ".join(text.split()))
    cover.save(PACKAGE / "cover_letter.docx")
    return ["highlights.docx", "cover_letter.docx"]


def _plain(text: str) -> str:
    """Turn the LaTeX abstractions of the abstract into plain submission-form text."""
    text = re.sub(r"\\dataset\{([^}]*)\}", r"\1", text)
    text = re.sub(r"\\emph\{([^}]*)\}", r"\1", text)
    text = re.sub(r"\$([^$]*)\$", lambda m: m.group(1).replace(r"\times", "x")
                  .replace("{", "").replace("}", ""), text)
    text = text.replace("\\%", "%").replace("~", " ")
    text = text.replace("---", " - ")
    return " ".join(text.split())


def write_metadata() -> list[str]:
    """Everything the Editorial Manager forms ask for, as copy-paste plain text."""
    tex = (PAPER / "main.tex").read_text(encoding="utf-8")
    abstract = tex.split("\\begin{abstract}")[1].split("\\end{abstract}")[0]
    keywords = [k.strip() for k in tex.split("\\begin{keyword}")[1]
                .split("\\end{keyword}")[0].replace("\n", " ").split("\\sep")]
    highlights = [line.strip() for line in
                  (PAPER / "highlights.txt").read_text(encoding="utf-8").splitlines()
                  if line.strip() and line.strip().lower() != "highlights"]
    body = [
        "# Fields to fill in the Editorial Manager submission forms",
        "",
        "## Article title",
        "",
        "When Should a Medical Image Classifier Abstain? A Cross-Modality Benchmark of "
        "Selective Prediction",
        "",
        "## Abstract (244 words; paste as plain text)",
        "",
        _plain(abstract),
        "",
        "## Keywords (6)",
        "",
        "; ".join(keywords),
        "",
        "## Authors",
        "",
        "- Corresponding author: Zhaoyang Li (single corresponding author)",
        "- E-mail: 212603010048@home.hpu.edu.cn",
        "- Affiliation: Henan Polytechnic University, No. 2001 Shiji Road, Jiaozuo "
        "454003, Henan, China",
        "",
        "## Highlights (also in highlights.docx)",
        "",
    ]
    body += [f"- {line}" for line in highlights]
    body += [
        "",
        "## Editorial Manager reminders",
        "",
        "- Article type: choose the full-length research article option in the list.",
        "- Upload the manuscript source (main.tex + references.bib + figures/ + tables/), "
        "not only the PDF; a PDF alone is not an acceptable source file.",
        "- Upload highlights.docx, cover_letter.docx, and the competing-interest "
        "declaration exported from https://declarations.elsevier.com/.",
        "- Suggested reviewers: optional for this journal; skip unless the form "
        "requires them.",
        "",
    ]
    (PACKAGE / "metadata_for_submission.md").write_text("\n".join(body), encoding="utf-8")
    return ["metadata_for_submission.md"]


def compile_test() -> tuple[bool, str]:
    """Compile the package in a clean directory; return (ok, log tail)."""
    with tempfile.TemporaryDirectory(prefix="cmpb_build_") as tmp:
        build = Path(tmp) / "submission"
        shutil.copytree(PACKAGE, build)
        commands = [
            ["pdflatex", "--enable-installer", "-interaction=nonstopmode", "main.tex"],
            ["bibtex", "main"],
            ["pdflatex", "--enable-installer", "-interaction=nonstopmode", "main.tex"],
            ["pdflatex", "--enable-installer", "-interaction=nonstopmode", "main.tex"],
        ]
        for command in commands:
            result = subprocess.run(command, cwd=build, capture_output=True, text=True,
                                    errors="replace")
            if command[0] == "pdflatex" and result.returncode not in (0, 1):
                return False, f"{command[-1]} exited {result.returncode}"
        log = (build / "main.log").read_text(encoding="utf-8", errors="replace")
        problems = [line for line in log.splitlines()
                    if line.startswith("!") or "Undefined control" in line
                    or "Warning: Reference" in line or "Warning: Citation" in line]
        pdf = build / "main.pdf"
        ok = not problems and pdf.exists()
        detail = f"{pdf.stat().st_size // 1024} KB" if pdf.exists() else "no PDF produced"
        if problems:
            detail += "; " + " | ".join(problems[:3])
        return ok, detail


def main() -> int:
    copied = copy_tree()
    editable = write_docx() + write_metadata()
    ok, detail = compile_test()
    print(f"package: {PACKAGE}")
    for name in copied + editable:
        print(f"  {name}")
    print(f"[{'ok' if ok else 'FAIL'}] clean-directory LaTeX build: {detail}")
    if not ok:
        return 1
    print("\nUpload checklist (Editorial Manager):")
    print("  1. main.tex  +  references.bib  +  figures/  +  tables/   (editable source;")
    print("     a PDF alone is not an acceptable source file per the CMPB guide)")
    print("  2. highlights.docx            (separate editable file, word 'highlights' in the name)")
    print("  3. cover_letter.docx")
    print("  4. competing-interest declaration exported from https://declarations.elsevier.com/")
    print("  5. single corresponding author: Zhaoyang Li (journal no longer accepts multiple)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
